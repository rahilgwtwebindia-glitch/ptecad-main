                    <h3 style="color:#fff;"><img src="assets/img/icons/span2.png" alt="">Blue Light Scanning Technology and Blue Light Systems</h3>
                    <div class="space16"></div>
                    <p>Blue Light is a version of this structured light scanning technology (White light scanning also falls under this technology umbrella). It operates by combining a projector, camera and lens system to allow data collection. The projector creates a pattern of light and dark areas on the object being measured. The camera takes an image of this pattern overlaid on the object. The projector and camera are at an angle to each other. Because the angle is well known, the focal distance is well known and the distance between the camera and projector are well known, each pixel of the image taken can be triangulated using the pattern of light and dark areas to create a point cloud. The pattern is typically straight lines or a well-known random pattern.</p>
                    <p>This technology makes use of a lens to magnify areas of the object being measured. The effect is to focus all of the camera’s image pixels into a smaller or larger area of the object. This allows more detail to be captured in smaller objects and larger areas to be covered in large objects. We have a complete set of lenses for each of our systems to accommodate your specific project requirements. Our experienced engineers know the exact options to use for your project to yield the best quality data in the shortest amount of time.
                    </p>
                    <p>The blue light resolution is excellent compared to other technologies such as laser scanning. The resolution is the spacing between point cloud points and is determined by the lens volume (the specific lenses used on the scanner) and the size of the camera in megapixels. This is opposed (and often confused with) accuracy which is the closeness of each measured point cloud point to the actual dimensional value. This excellent resolution allows for the recreation of very small details and is generally required for highly detailed reverse engineering projects.</p>
                   

