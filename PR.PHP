function requestAQuoteFormSubmit(event) {
  var name  = $("#arkRequestForm :input[name='name']").val();
  var email = $("#arkRequestForm :input[name='email']").val();
  var phone = $("#arkRequestForm :input[name='phone']").val();
  var pattern  = /^\b[A-Z0-9._%-]+@[A-Z0-9.-]+\.[A-Z]{2,4}\b$/i;
  var namepatt = /^[a-zA-Z][a-zA-Z '-]{1,98}[a-zA-Z]$/;
  var filter   = /^[0-9-+]+$/;

  function fail(sel, msg) {
    $(sel).css("display", "block").html(msg);
    return false;
  }
  function ok(sel) {
    $(sel).css("display", "none").html('');
  }

  if (name.length < 3)          return fail("#Request_name_error", 'Please fill the Fields');
  ok("#Request_name_error");
  if (!namepatt.test(name))     return fail("#Request_name_error", 'Please enter correct name');
  ok("#Request_name_error");
  if (phone.length != 10)       return fail("#Request_phone_error", 'Please enter correct phone no.');
  ok("#Request_phone_error");
  if (!filter.test(phone)) {
    setTimeout(function () { $('#Request_phone_error').fadeOut('fast'); }, 1000);
    return fail("#Request_phone_error", 'Please fill the correct phone Number');
  }
  ok("#Request_phone_error");
  if (!pattern.test(email))     return fail("#Request_email_error", 'Please enter correct email.');
  ok("#Request_email_error");

  if (event && event.preventDefault) event.preventDefault();

  var formdata = $('#arkRequestForm').serialize();
  $('#requestAQuoteFormSubmitButton').html('Please Wait..');
  $.ajax({
    type: "post",
    url: 'https://www.arkinfo.in/arkInfoSave',
    data: formdata,
    success: function (data) {
      if (data.status === 'success') {
        $('#requestformModal').modal('hide');
        $('#requestAQuoteFormSubmitButton').html('Submit');
        $('#arkRequestForm')[0].reset();
        window.location.href = data.redirect; // thank-you page redirect
      }
    },
    error: function (jqXHR) {
      $('#requestAQuoteFormSubmitButton').html('Submit');
      alert("An error occurred: " + (jqXHR.responseJSON?.message || "Unknown error"));
    }
  });
}

